package main

import (
	"flag"
	"fmt"
	"io"
	"sort"
	"strings"
)

// This file implements `gitty completion <shell>`, which prints a completion
// script for bash, zsh or fish. The scripts are generated from the command
// table in commands.go and each command's real flag set, so a flag added to
// gitty is completed without anyone remembering to update a script.
//
// A group argument is completed as a directory: inside a workspace, groups
// are directories, and the argument is relative to the one the shell is in.

// completionShells are the supported shells, in the order they are listed.
var completionShells = []string{"bash", "zsh", "fish"}

// runCompletion prints the script for the requested shell.
func runCompletion(w io.Writer, args []string) error {
	if len(args) != 1 {
		return usageErrf("usage: gitty completion <%s>", strings.Join(completionShells, "|"))
	}
	switch args[0] {
	case "bash":
		writeBashCompletion(w)
	case "zsh":
		writeZshCompletion(w)
	case "fish":
		writeFishCompletion(w)
	default:
		return usageErrf("unknown shell %q: choose one of %s", args[0], strings.Join(completionShells, ", "))
	}
	return nil
}

// completionFlag is one flag as the scripts need it.
type completionFlag struct {
	name  string
	usage string
	bool  bool // takes no value
}

// commandFlags lists a command's flags by declaring them on a scratch set.
func commandFlags(c command) []completionFlag {
	if c.declare == nil {
		return nil
	}
	fs := flag.NewFlagSet(c.name, flag.ContinueOnError)
	c.declare(fs)
	var out []completionFlag
	fs.VisitAll(func(fl *flag.Flag) {
		isBool := false
		if bf, ok := fl.Value.(boolFlag); ok && bf.IsBoolFlag() {
			isBool = true
		}
		out = append(out, completionFlag{name: fl.Name, usage: fl.Usage, bool: isBool})
	})
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}

// commandNames returns every command's name, in table order.
func commandNames() []string {
	names := make([]string, 0, len(commands))
	for _, c := range commands {
		names = append(names, c.name)
	}
	return names
}

// subwords are the fixed arguments of the commands that take one.
var subwords = map[string][]string{
	"completion": completionShells,
	"agent":      {"schema"},
}

// plainDescription makes a flag's usage text safe inside the quoting each
// script uses: no quotes, no brackets (zsh delimiters), no colons (zsh and
// fish field separators), on one line.
func plainDescription(s string) string {
	r := strings.NewReplacer(
		"'", "", "\"", "", "`", "",
		"[", "(", "]", ")", ":", " -",
		"\n", " ",
	)
	return strings.Join(strings.Fields(r.Replace(s)), " ")
}

func writeBashCompletion(w io.Writer) {
	fmt.Fprintln(w, "# bash completion for gitty — generated by `gitty completion bash`")
	fmt.Fprintln(w, "# Install: gitty completion bash > ~/.local/share/bash-completion/completions/gitty")
	fmt.Fprintln(w, "_gitty() {")
	fmt.Fprintln(w, "    local cur cmd")
	fmt.Fprintln(w, "    COMPREPLY=()")
	fmt.Fprintln(w, `    cur="${COMP_WORDS[COMP_CWORD]}"`)
	fmt.Fprintln(w, `    cmd="${COMP_WORDS[1]}"`)
	fmt.Fprintln(w, `    if [ "$COMP_CWORD" -eq 1 ]; then`)
	fmt.Fprintf(w, "        COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )\n", strings.Join(commandNames(), " "))
	fmt.Fprintln(w, "        return")
	fmt.Fprintln(w, "    fi")
	fmt.Fprintln(w, `    case "$cmd" in`)
	for _, c := range commands {
		fmt.Fprintf(w, "    %s)\n", c.name)
		flags := commandFlags(c)
		var names []string
		for _, f := range flags {
			names = append(names, "--"+f.name)
		}
		if len(flags) > 0 {
			fmt.Fprintln(w, `        if [[ "$cur" == -* ]]; then`)
			fmt.Fprintf(w, "            COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )\n", strings.Join(names, " "))
			fmt.Fprintln(w, "            return")
			fmt.Fprintln(w, "        fi")
		}
		switch {
		case c.takesGroup:
			fmt.Fprintln(w, `        COMPREPLY=( $(compgen -d -- "$cur") )`)
		case len(subwords[c.name]) > 0:
			fmt.Fprintf(w, "        COMPREPLY=( $(compgen -W \"%s\" -- \"$cur\") )\n", strings.Join(subwords[c.name], " "))
		}
		fmt.Fprintln(w, "        ;;")
	}
	fmt.Fprintln(w, "    esac")
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w, "complete -o filenames -F _gitty gitty")
}

func writeZshCompletion(w io.Writer) {
	fmt.Fprintln(w, "#compdef gitty")
	fmt.Fprintln(w, "# zsh completion for gitty — generated by `gitty completion zsh`")
	fmt.Fprintln(w, "# Install: gitty completion zsh > \"${fpath[1]}/_gitty\" (then restart the shell)")
	fmt.Fprintln(w, "_gitty() {")
	fmt.Fprintln(w, "  local -a commands")
	fmt.Fprintln(w, "  commands=(")
	for _, c := range commands {
		fmt.Fprintf(w, "    '%s:%s'\n", c.name, plainDescription(c.summary))
	}
	fmt.Fprintln(w, "  )")
	fmt.Fprintln(w, "  local state")
	fmt.Fprintln(w, "  _arguments -C '1:command:->command' '*::argument:->args'")
	fmt.Fprintln(w, "  case $state in")
	fmt.Fprintln(w, "    command) _describe 'command' commands ;;")
	fmt.Fprintln(w, "    args)")
	fmt.Fprintln(w, "      case $words[1] in")
	for _, c := range commands {
		var specs []string
		for _, f := range commandFlags(c) {
			if f.bool {
				specs = append(specs, fmt.Sprintf("'--%s[%s]'", f.name, plainDescription(f.usage)))
			} else {
				specs = append(specs, fmt.Sprintf("'--%s=[%s]'", f.name, plainDescription(f.usage)))
			}
		}
		switch {
		case c.takesGroup:
			specs = append(specs, "'1:group:_path_files -/'")
		case len(subwords[c.name]) > 0:
			specs = append(specs, fmt.Sprintf("'1:argument:(%s)'", strings.Join(subwords[c.name], " ")))
		}
		if len(specs) == 0 {
			continue
		}
		fmt.Fprintf(w, "        %s) _arguments %s ;;\n", c.name, strings.Join(specs, " "))
	}
	fmt.Fprintln(w, "      esac ;;")
	fmt.Fprintln(w, "  esac")
	fmt.Fprintln(w, "}")
	fmt.Fprintln(w, `_gitty "$@"`)
}

func writeFishCompletion(w io.Writer) {
	fmt.Fprintln(w, "# fish completion for gitty — generated by `gitty completion fish`")
	fmt.Fprintln(w, "# Install: gitty completion fish > ~/.config/fish/completions/gitty.fish")
	fmt.Fprintln(w, "complete -c gitty -f")
	for _, c := range commands {
		fmt.Fprintf(w, "complete -c gitty -n __fish_use_subcommand -a %s -d '%s'\n", c.name, plainDescription(c.summary))
	}
	for _, c := range commands {
		cond := fmt.Sprintf("'__fish_seen_subcommand_from %s'", c.name)
		for _, f := range commandFlags(c) {
			value := ""
			if !f.bool {
				value = " -r"
			}
			fmt.Fprintf(w, "complete -c gitty -n %s -l %s%s -d '%s'\n", cond, f.name, value, plainDescription(f.usage))
		}
		switch {
		case c.takesGroup:
			fmt.Fprintf(w, "complete -c gitty -n %s -a '(__fish_complete_directories)'\n", cond)
		case len(subwords[c.name]) > 0:
			fmt.Fprintf(w, "complete -c gitty -n %s -a '%s'\n", cond, strings.Join(subwords[c.name], " "))
		}
	}
}
